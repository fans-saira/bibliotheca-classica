"""Generate the final ConTeXt chart page from the lexical study results."""
from pathlib import Path
import json

base = Path(__file__).resolve().parent
data = json.loads((base / 'fontes/estudo-lexical/resultado-lexical.json').read_text(encoding='utf-8'))
labels = ['Básico fundamental', 'Característico da tragédia',
          'Atestação exclusiva em Ésquilo', 'Outros contextos até 456 a.C.',
          'Ainda não classificados']
colors = ['accent', 'ornament', 'lexicalblue', 'lexicalsage', 'filete']
categories = data['categorias']
total = data['denominador_ocorrencias_comuns']
assert sum(c['ocorrencias'] for c in categories) == total

out = [r'''% Generated by gerar-grafico-lexical.py; do not edit the percentages here.
\definecolor[lexicalblue][h=56757C]
\definecolor[lexicalsage][h=78816C]
\definecolor[lexicalgray][h=81756B]
\switchtobodyfont[11pt]
\setupinterlinespace[line=15pt]
{\switchtobodyfont[9pt]\bf\color[accent]{LEVANTAMENTO PRELIMINAR}}\par
\blank[3mm]
{\switchtobodyfont[23pt]O vocabulário de {\it Persas}}\par
\blank[3mm]\useMPgraphic{meandro}\par\blank[6mm]
Distribuição das 4.860 ocorrências de vocabulário comum. Cada ocorrência entra
em uma única categoria.\par
\blank[6mm]
\startMPcode
 path disk, wedge;
 pair center;
 numeric a, b;
 center := (59mm,40mm);
 disk := fullcircle scaled 70mm rotated 90 shifted center;
''']
angle = 0
for c, color in zip(categories, colors):
    end = angle + 8*c['ocorrencias']/total
    out.append(f''' a := {angle:.10f}; b := {end:.10f};
 wedge := center -- subpath (a,b) of disk -- cycle;
 fill wedge withcolor \\MPcolor{{{color}}};
 draw wedge withpen pencircle scaled .6pt withcolor white;
''')
    angle = end
out.append(r''' setbounds currentpicture to unitsquare xscaled 118mm yscaled 80mm;
\stopMPcode
\blank[3mm]
\startMPcode
 numeric w, y;
 w := 118mm;
''')
for i, (c, label, color) in enumerate(zip(categories, labels, colors)):
    pct = f"{100*c['ocorrencias']/total:.2f}".replace('.', ',')
    label_color = 'lexicalgray' if color == 'filete' else color
    out.append(f''' y := {32-i*7}mm;
 label.rt(textext("\\switchtobodyfont[11pt]{label}"),(6mm,y+1.5mm));
 label.lft(textext("\\switchtobodyfont[11pt]\\bf\\color[{label_color}]{{{pct}\\%}}"),(w,y+1.5mm));
 fill unitsquare xscaled 3mm yscaled 3mm shifted (0,y)
   withcolor \\MPcolor{{{color}}};
''')
out.append(r''' setbounds currentpicture to unitsquare xscaled 118mm yscaled 37mm;
\stopMPcode
\blank[3mm]
{\switchtobodyfont[10pt]\setupinterlinespace[line=14pt]
As quatro categorias seguem a ordem da legenda, descontando as anteriores.\par
\blank[3mm]
O setor cinza reúne 588 ocorrências cuja atribuição ainda não foi demonstrada;
não constitui um quinto contexto literário.\par
\blank[3mm]
Básico: repertório combinado de 1.286 lemas. Os 327 nomes próprios e gentílicos
foram separados da contagem.\par
\blank[3mm]
Ésquilo: exclusividade de atestação do lema ou sentido na documentação
consultada. Outros contextos: usos épicos e líricos positivamente identificados
até 456 a.C.; levantamento ainda não exaustivo.\par
\blank[3mm]
As atribuições permanecem em revisão. Fontes, critérios e classificação por
palavra estão na documentação do projeto.\par}
''')
(base / 'grafico-lexical.tex').write_text(''.join(out), encoding='utf-8')
print('Pie chart generated:', total, 'occurrences; four categories and unclassified remainder.')
